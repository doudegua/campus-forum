-- 010 —— 种子数据：帖子类型（版块）
--
-- 这是**唯一**进仓库的种子数据，内容是四个正经的校园版块。
--
-- 为什么单独一个文件、而不是塞进 schema.sql：
--   schema.sql 的职责是"建结构"，每次启动重放；种子数据是"灌内容"，
--   只在库第一次建起来时该做一次。两者混在一起以后很难分辨
--   "这库为什么长这样"和"这库为什么有这些数据"。
--   所以结构走 schema.sql，数据走这里，由 Docker 的初始化目录执行一次。
--
-- 为什么用 INSERT IGNORE 而不是 INSERT：
--   这个文件要能重复执行而不炸（道理和 schema.sql 只放幂等语句一样）。
--   换成 INSERT，第二次执行会因为主键重复报 ERROR 1062，
--   而 mysql 批处理模式下**遇到错误就中止剩余语句** —— 库就半初始化了。
--
-- 为什么要把 id 写死：
--   前端下拉框拿 choice 的 value 就是这里的 id。写死了，
--   删除/重灌这个库之后，已经存在的帖子（db_topic.type）还能对上正确的版块。
--   让 id 自增的话，重灌一次版块 id 就可能整体位移，老帖子会集体挂到错的版块下。
--
-- 注意：**这里不灌任何用户和帖子。**
--   用户表里有真实邮箱，帖子表里有一批测试帖（也有几条不适合公开的），
--   而这是一个要推到公开仓库的文件 —— 只能放这种"本身就是项目常量"的数据。
-- ===========================================================================

